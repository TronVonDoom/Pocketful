// ---------------------------------------------------------------------- version

// One place the app's version is written down. The Android manifest, the Settings screen
// and the in-app updater all read it from here, so there is no way for the number the app
// displays to disagree with the number it compares against a GitHub release tag.
val appVersionName: String = providers.gradleProperty("pocketful.versionName").get()
val appVersionCode: Int = providers.gradleProperty("pocketful.versionCode").get().toInt()

/**
 * Hands [appVersionName] to common code as a generated source file.
 *
 * The alternative -- BuildConfig -- only exists on the Android target, and the code that
 * needs the version most (the updater's "is the release newer than me" check) is common.
 * A four-line generated file costs less than an expect/actual pair per platform.
 */
val generateAppVersion by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/version/commonMain/kotlin")

    // The finished file, not the ingredients. Registering the version numbers as the only
    // inputs made the task up to date whenever they had not changed -- including after an
    // edit to the text below, which then sat in the build directory as a stale file that a
    // clean build would silently replace with something different. The whole output is the
    // input, so editing a line of it is a change Gradle can see.
    val source = """
            package app.pocketful

            /**
             * What this build calls itself.
             *
             * Generated by the `generateAppVersion` Gradle task from `pocketful.versionName`
             * and `pocketful.versionCode` in gradle.properties. Do not edit -- edit those.
             */
            object AppVersion {
                const val NAME: String = "$appVersionName"
                const val CODE: Int = $appVersionCode

                /** The git tag a release of this version is published under. */
                val tag: String get() = "v${'$'}NAME"

                /**
                 * How a build names itself on screen: `v0.3.2_009`.
                 *
                 * The build number is padded rather than parenthesised. `v0.3.2 (9)` reads
                 * as a version with a footnote after it; the padded suffix reads as part of
                 * the same identifier, which is what it is -- and three digits means the
                 * hundredth build sorts and aligns with the ninth instead of shunting the
                 * text along by a character every time it rolls over.
                 */
                val label: String get() = "v${'$'}NAME" + "_" + CODE.toString().padStart(3, '0')
            }

            """.trimIndent()

    inputs.property("source", source)
    outputs.dir(outputDir)
    doLast {
        val target = outputDir.get().asFile.resolve("app/pocketful")
        target.mkdirs()
        target.resolve("AppVersion.kt").writeText(source)
    }
}

// ---------------------------------------------------------------------- signing

/**
 * Release signing, from a file that is never committed or from CI secrets.
 *
 * Falls back to the debug key when neither is present, which keeps `assembleRelease`
 * working on a fresh clone. That fallback matters more than it looks: an APK can only
 * replace an installed app if both are signed by the same key, so a self-updating build
 * signed with a throwaway key would install once and then refuse every update after it.
 * Whichever key you ship the first APK with is the key every later one must use.
 */
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use(::load)
}

// Blank counts as absent. CI sets these variables unconditionally and leaves them empty
// when no signing secrets are configured, and an empty string is a path -- `file("")`
// resolves to the project directory and fails the build with something that looks nothing
// like "you have no keystore".
fun signingSecret(property: String, environment: String): String? =
    (keystoreProperties.getProperty(property)
        ?: providers.environmentVariable(environment).orNull)
        ?.takeIf { it.isNotBlank() }

val releaseKeystore: String? = signingSecret("storeFile", "POCKETFUL_KEYSTORE_FILE")

kotlin {
    androidTarget {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_21)
        }
    }

    sourceSets {
        // The `compose.*` accessors are deprecated in favour of explicit coordinates, but
        // material3 is published on its own version track (stable stops at 1.9.0 while the
        // rest of Compose is at 1.12.0). The plugin resolves a combination that is actually
        // tested together, so keep the accessors until material3 catches up.
        commonMain.dependencies {
            implementation(compose.runtime)
            implementation(compose.foundation)
            implementation(compose.material3)
            implementation(compose.ui)
            implementation(compose.components.resources)
            implementation(libs.kotlinx.coroutines.core)
            implementation(libs.kotlinx.serialization.json)
            implementation(libs.ktor.client.core)
            implementation(libs.ktor.client.content.negotiation)
            implementation(libs.ktor.serialization.kotlinx.json)
            implementation(libs.coil.compose)
            implementation(libs.coil.network.ktor3)
        }
        commonMain.get().kotlin.srcDir(generateAppVersion)
        androidMain.dependencies {
            implementation(compose.preview)
            implementation(libs.androidx.activity.compose)
            implementation(libs.androidx.core.ktx)
            // The engine is only needed where the app actually runs. Ktor discovers it at
            // runtime, so common code can build an HttpClient without naming a platform.
            implementation(libs.ktor.client.okhttp)
        }
    }
}

/**
 * Resources are addressed from common code, so the generated accessor has to live at a
 * package this app actually owns rather than the plugin's default, which is derived from
 * the Gradle group and module name and changes if either is renamed.
 */
compose.resources {
    publicResClass = true
    packageOfResClass = "app.pocketful.resources"
    generateResClass = always
}

android {
    namespace = "app.pocketful"
    compileSdk = libs.versions.androidCompileSdk.get().toInt()

    defaultConfig {
        applicationId = "app.pocketful"
        minSdk = libs.versions.androidMinSdk.get().toInt()
        targetSdk = libs.versions.androidTargetSdk.get().toInt()
        versionCode = appVersionCode
        versionName = appVersionName
    }

    buildFeatures {
        compose = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_21
        targetCompatibility = JavaVersion.VERSION_21
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = signingSecret("storePassword", "POCKETFUL_KEYSTORE_PASSWORD")
                keyAlias = signingSecret("keyAlias", "POCKETFUL_KEY_ALIAS")
                keyPassword = signingSecret("keyPassword", "POCKETFUL_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        getByName("release") {
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release")
                ?: signingConfigs.getByName("debug")
        }
    }
}
